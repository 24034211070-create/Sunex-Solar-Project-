    // BASIC FIELD UPDATE
    // ==================================================

    const updateField = (field, value) => {
        setData((prev) => ({
            ...prev,
            [field]: value,
        }));
    };

    // ==================================================
    // NESTED FIELD UPDATE
    // ==================================================

    const updateNestedField = (
        section,
        field,
        value
    ) => {
        setData((prev) => ({
            ...prev,
            [section]: {
                ...(prev[section] || {}),
                [field]: value,
            },
        }));
    };


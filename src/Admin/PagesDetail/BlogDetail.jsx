const isObject = (value) => {
    return (
        value !== null &&
        typeof value === "object" &&
        !Array.isArray(value)
    );
};

const getPageName = (page) => {
    return String(page?.pageName || page?.page_name || "")
        .trim()
        .toLowerCase();
};

const getSectionName = (page) => {
    return String(page?.sectionName || page?.section_name || "")
        .trim()
        .toLowerCase();
};

const getContentObject = (page) => {
    if (!page?.content) {
        return {};
    }

    if (typeof page.content === "object") {
        return page.content;
    }

    try {
        return JSON.parse(page.content);
    } catch {
        return {};
    }
};

const mergeBlogData = (content) => {
    const safeContent = isObject(content) ? content : {};

    return {
        ...defaultData,
        ...safeContent,

        hero: {
            ...defaultData.hero,
            ...(isObject(safeContent.hero)
                ? safeContent.hero
                : {}),
        },

        intro: {
            ...defaultData.intro,
            ...(isObject(safeContent.intro)
                ? safeContent.intro
                : {}),
        },

        installation: {
            ...defaultData.installation,
            ...(isObject(safeContent.installation)
                ? safeContent.installation
                : {}),
        },

        social: {
            ...defaultData.social,
            ...(isObject(safeContent.social)
                ? safeContent.social
                : {}),
        },

        comments: {
            ...defaultData.comments,
            ...(isObject(safeContent.comments)
                ? safeContent.comments
                : {}),
        },

        installationSteps: Array.isArray(
            safeContent.installationSteps
        )
            ? safeContent.installationSteps
            : [...defaultData.installationSteps],

        tags: Array.isArray(safeContent.tags)
            ? safeContent.tags
            : [...defaultData.tags],
    };
};

